-- =====================================================================
-- Tenants, users and roles (ADR010, ADR012). Kept apart from the content schema (V1) so user management can move
-- to a service of its own: no content table has a foreign key to these tables, they only store tenant_id and
-- user ids. That is also why the fixed-tenant security mode works with any tenant id.
--
-- Users sign in through Keycloak: users.external_id is the token's subject. Keycloak only authenticates; roles live
-- here (roles, user_roles).
-- =====================================================================

-- INDIVIDUAL: a user's own workspace. ORGANIZATION: shared by several users (later).
-- LIBRARY: shared sample content everyone may read; no members, only an ADMIN changes it.
CREATE TABLE tenants (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    type VARCHAR(30) NOT NULL,
    name VARCHAR(200) NOT NULL,
    -- the user the tenant was created for, if any
    owner_user_id BIGINT NULL,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    created_by BIGINT NULL,
    updated_by BIGINT NULL,

    CONSTRAINT chk_tenants_type CHECK (type IN ('INDIVIDUAL', 'ORGANIZATION', 'LIBRARY'))
);

CREATE TABLE users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    external_id VARCHAR(255) NOT NULL,
    -- every user belongs to exactly one tenant; NULL only for the system user (id 0)
    tenant_id BIGINT NULL,
    email VARCHAR(320) NULL,
    display_name VARCHAR(200) NULL,
    last_seen_at TIMESTAMP NULL,
    -- Settings the user chose for the app (theme, ...), as JSON so new settings need no migration. NULL until the
    -- user changes one; the app then uses its defaults.
    preferences_json JSONB NULL,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    created_by BIGINT NULL,
    updated_by BIGINT NULL,

    CONSTRAINT uk_users_external_id UNIQUE (external_id),
    CONSTRAINT fk_users_tenant FOREIGN KEY (tenant_id) REFERENCES tenants(id),
    CONSTRAINT chk_users_tenant CHECK (id = 0 OR tenant_id IS NOT NULL)
);

CREATE INDEX idx_users_tenant_id ON users(tenant_id);

ALTER TABLE tenants
    ADD CONSTRAINT fk_tenants_owner FOREIGN KEY (owner_user_id) REFERENCES users(id) ON DELETE SET NULL;

