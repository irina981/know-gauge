-- Workspace invitations (ADR015): an ADMIN creates a workspace (tenant) and invites people by email. Accepting puts
-- the user into that workspace (users.tenant_id) with the invited role (user_roles); a user who had a workspace
-- before leaves it, and it keeps its content. Libraries are never invited to: they have no users (V5 trigger).
CREATE TABLE workspace_invitations (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id BIGINT NOT NULL,
    -- stored lower-cased, so the unique constraint below catches the same address typed differently
    email VARCHAR(320) NOT NULL,
    -- the tenant role the user gets on accepting (TENANT_ADMIN for now)
    role_code VARCHAR(30) NOT NULL,
    public_token VARCHAR(64) NOT NULL,
    sent_at TIMESTAMP NULL,
    send_count INTEGER NOT NULL DEFAULT 0,
    send_error TEXT NULL,
    accepted_at TIMESTAMP NULL,
    accepted_user_id BIGINT NULL,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    created_by BIGINT NULL,
    updated_by BIGINT NULL,

    CONSTRAINT fk_workspace_invitations_tenant FOREIGN KEY (tenant_id) REFERENCES tenants(id) ON DELETE CASCADE,
    CONSTRAINT fk_workspace_invitations_role FOREIGN KEY (role_code) REFERENCES roles(code),
    CONSTRAINT fk_workspace_invitations_user FOREIGN KEY (accepted_user_id) REFERENCES users(id) ON DELETE SET NULL,
    CONSTRAINT uk_workspace_invitations_token UNIQUE (public_token),
    CONSTRAINT uk_workspace_invitations_tenant_email UNIQUE (tenant_id, email)
);

CREATE INDEX idx_workspace_invitations_tenant_id ON workspace_invitations (tenant_id);
-- First sign-in looks up a pending invitation by email.
CREATE INDEX idx_workspace_invitations_pending_email ON workspace_invitations (email) WHERE accepted_at IS NULL;
