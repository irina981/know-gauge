    ADD CONSTRAINT fk_test_questions_current_version
    FOREIGN KEY (current_version_id) REFERENCES test_question_versions(id) ON DELETE SET NULL;

-- Create test_question_version_options table (4 options per version)
CREATE TABLE test_question_version_options (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    version_id BIGINT NOT NULL,
    option_letter VARCHAR(1) NOT NULL,
    text TEXT NOT NULL,
    correct BOOLEAN NOT NULL,
    flagged BOOLEAN NOT NULL DEFAULT FALSE,
    suggested_text TEXT,
    flag_reason TEXT,

    CONSTRAINT fk_tqv_options_version FOREIGN KEY (version_id) REFERENCES test_question_versions(id) ON DELETE CASCADE,
    CONSTRAINT uk_tqv_options_version_letter UNIQUE (version_id, option_letter),
    CONSTRAINT chk_tqv_options_letter CHECK (option_letter IN ('A','B','C','D'))
);

-- Create test_events table (append-only history trail)
CREATE TABLE test_events (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id BIGINT NOT NULL,
    test_id BIGINT NOT NULL,
    question_id BIGINT,
    event_type VARCHAR(40) NOT NULL,
    from_version_id BIGINT,
    to_version_id BIGINT,
    actor_user_id BIGINT,  -- NULL = system
    comment TEXT,
    payload_json JSONB,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_test_events_test FOREIGN KEY (test_id) REFERENCES tests(id) ON DELETE CASCADE,
    CONSTRAINT fk_test_events_question FOREIGN KEY (question_id) REFERENCES test_questions(id) ON DELETE CASCADE,
    CONSTRAINT chk_test_events_type CHECK (event_type IN (
        'TEST_CREATED', 'TEST_GENERATED', 'TEST_REQUIRES_REVIEW', 'TEST_REVIEWED', 'TEST_FAILED',
        'TEST_PUBLISHED', 'TEST_UNPUBLISHED', 'QUESTION_GENERATED', 'OPTION_FLAGGED', 'FIX_ACCEPTED', 'QUESTION_REGENERATED',
        'REGENERATION_FAILED', 'QUESTION_MANUALLY_REPLACED'))
);

CREATE INDEX idx_test_events_test_id_created_at ON test_events(test_id, created_at, id);
CREATE INDEX idx_test_events_question_id ON test_events(question_id);

