-- Create topics table
CREATE TABLE topics (
	id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	tenant_id BIGINT NOT NULL,
    parent_id BIGINT,
    name VARCHAR(255) NOT NULL,
    description TEXT,
    path VARCHAR(500),
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    created_by BIGINT NOT NULL,
	updated_by BIGINT NOT NULL,

    CONSTRAINT fk_topics_parent FOREIGN KEY (parent_id) REFERENCES topics(id) ON DELETE CASCADE,

    -- Prevent duplicate topic names under the same parent
    CONSTRAINT uk_topics_parent_name UNIQUE (parent_id, name),

    -- Ensure canonical path uniqueness
    CONSTRAINT uk_topics_path UNIQUE (path)
);

CREATE INDEX idx_topics_parent_id ON topics(parent_id);
CREATE INDEX idx_topics_path_prefix ON topics (path text_pattern_ops);

-- Create documents table
CREATE TABLE documents (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id BIGINT NOT NULL,
    topic_id BIGINT NOT NULL,
    title VARCHAR(500),
    original_file_name VARCHAR(500) NOT NULL,
    content_type VARCHAR(100) NOT NULL,
    file_size_bytes BIGINT NOT NULL,
    storage_key VARCHAR(1000),
    checksum VARCHAR(64) NOT NULL,
    version INTEGER NOT NULL,
    status VARCHAR(50) NOT NULL,
    ingested_at TIMESTAMP,
    error_message TEXT,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    created_by BIGINT NOT NULL,
	updated_by BIGINT NOT NULL,
    
    CONSTRAINT fk_documents_topic FOREIGN KEY (topic_id) REFERENCES topics(id) ON DELETE CASCADE,
    CONSTRAINT chk_documents_status CHECK (status IN ('UPLOADED','INGESTING','INGESTED','FAILED')),
    CONSTRAINT uq_documents_topic_filename UNIQUE (topic_id, original_file_name),
    CONSTRAINT uq_documents_topic_contenthash UNIQUE (topic_id, checksum)
);

CREATE INDEX idx_documents_topic_id ON documents(topic_id);
CREATE INDEX idx_documents_status ON documents(status);
CREATE INDEX idx_documents_topic_status ON documents(topic_id, status);

-- Create document_sections table
CREATE TABLE document_sections (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    document_id BIGINT NOT NULL,
    title VARCHAR(500) NOT NULL,
    order_index INTEGER NOT NULL,
    start_page INTEGER,
    end_page INTEGER,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    created_by BIGINT NOT NULL,
	updated_by BIGINT NOT NULL,

    CONSTRAINT fk_document_sections_document FOREIGN KEY (document_id) REFERENCES documents(id) ON DELETE CASCADE
);

CREATE INDEX idx_document_sections_document_id ON document_sections(document_id);

-- Create document_chunks table
CREATE TABLE document_chunks (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id BIGINT NOT NULL,
    topic_id BIGINT NOT NULL,
    document_id BIGINT NOT NULL,
    document_version INTEGER NOT NULL DEFAULT 1,
    section_id BIGINT,
    ordinal INTEGER NOT NULL,
    chunk_text TEXT NOT NULL,
    checksum VARCHAR(64),
    start_page INTEGER,
    end_page INTEGER,
    char_start INTEGER,
    char_end INTEGER,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    created_by BIGINT NOT NULL,
	updated_by BIGINT NOT NULL,

    CONSTRAINT fk_document_chunks_document FOREIGN KEY (document_id) REFERENCES documents(id) ON DELETE CASCADE,
    CONSTRAINT fk_document_chunks_topic FOREIGN KEY (topic_id) REFERENCES topics(id) ON DELETE CASCADE,
    CONSTRAINT fk_document_chunks_section FOREIGN KEY (section_id) REFERENCES document_sections(id) ON DELETE SET NULL,
    CONSTRAINT uk_document_chunks_ordinal UNIQUE (tenant_id, document_id, document_version, ordinal)
);

-- Useful filtering indexes
CREATE INDEX idx_document_chunks_docver
    ON document_chunks(tenant_id, document_id, document_version);

CREATE INDEX idx_document_chunks_topic
    ON document_chunks(tenant_id, topic_id);

-- Optional: fast lookup by checksum if you want to dedupe or detect duplicates
CREATE INDEX idx_document_chunks_checksum
    ON document_chunks(tenant_id, checksum);
    
-- For ordered reads and “fetch neighbors by ordinal”
CREATE INDEX idx_chunks_tenant_docver_ordinal
    ON document_chunks(tenant_id, document_id, document_version, ordinal);

-- Create tests table
CREATE TABLE tests (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id BIGINT NOT NULL,
    difficulty VARCHAR(50) NOT NULL,
    coverage_mode VARCHAR(30) NOT NULL DEFAULT 'BALANCED_PER_DOC_CHUNKS',
    avoid_repeats BOOLEAN NOT NULL DEFAULT TRUE,
    question_count INTEGER NOT NULL,
    answer_cardinality VARCHAR(30) NOT NULL DEFAULT 'SINGLE_CORRECT',
    status VARCHAR(50) NOT NULL,
    prompt_template_id VARCHAR(100),
    generation_model VARCHAR(100),
    language VARCHAR(10) NOT NULL DEFAULT 'EN',
    generation_params_json JSONB,
    generation_started_at TIMESTAMP NULL,
    generation_finished_at TIMESTAMP NULL,
    generation_failed_at TIMESTAMP NULL,
    generation_error_message TEXT NULL,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    created_by BIGINT NOT NULL,
    updated_by BIGINT NOT NULL,

    CONSTRAINT chk_tests_status CHECK (status IN ('CREATED', 'GENERATED', 'REQUIRES_REVIEW', 'REVIEWED', 'FAILED', 'PUBLISHED')),
    CONSTRAINT chk_tests_difficulty CHECK (difficulty IN ('EASY', 'MEDIUM', 'HARD')),
    CONSTRAINT chk_tests_coverage_mode CHECK (coverage_mode IN ('BALANCED_PER_DOCS', 'BALANCED_PER_DOC_CHUNKS', 'FOCUSED')),
    CONSTRAINT chk_tests_answer_cardinality CHECK (answer_cardinality IN ('SINGLE_CORRECT', 'MULTIPLE_CORRECT')),
    CONSTRAINT chk_tests_language CHECK (language IN ('EN','DE','FR','ES','IT','SR')),
    CONSTRAINT chk_tests_question_count CHECK (question_count > 0),

    -- Optional sanity: lifecycle ordering (allows NULLs)
   CONSTRAINT chk_tests_generation_lifecycle CHECK (
        (generation_finished_at IS NULL OR generation_started_at IS NULL OR generation_started_at <= generation_finished_at)
        AND (generation_failed_at IS NULL OR generation_started_at IS NULL OR generation_started_at <= generation_failed_at)
    )
);

-- Primary lifecycle queries (tenant + status)
CREATE INDEX idx_tests_tenant_status
ON tests(tenant_id, status);

-- Tenant + created_at (for sorting test history)
CREATE INDEX idx_tests_tenant_created_at
ON tests(tenant_id, created_at DESC);

-- Optional: generation model analytics / debugging
CREATE INDEX idx_tests_generation_model
ON tests(generation_model);

-- Optional: status only (useful for background workers scanning GENERATING/FAILED)
CREATE INDEX idx_tests_status
ON tests(status);

-- Optional: quickly find stuck generations or analyze performance
CREATE INDEX idx_tests_tenant_generation_started_at
ON tests(tenant_id, generation_started_at DESC);

CREATE INDEX idx_tests_tenant_generation_failed_at
ON tests(tenant_id, generation_failed_at DESC);



-- =====================================================================
-- Test questions: versioned (see docs/adr/ADR001-review-process.md)
--   test_questions          = stable slot (position in test, status, pointer to current version)
--   test_question_versions  = immutable content snapshots (insert-only)
--   test_question_version_options = 4 options per version (insert-only)
--   generation_runs         = every LLM call (generation, regeneration, verification)
--   test_events             = append-only history trail of a test and its questions
-- =====================================================================

-- Create test_questions table (slot)
CREATE TABLE test_questions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id BIGINT NOT NULL,
    test_id BIGINT NOT NULL,
    question_index INTEGER NOT NULL,
    status VARCHAR(20) NOT NULL DEFAULT 'OK',
    current_version_id BIGINT,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    created_by BIGINT NOT NULL,
    updated_by BIGINT NOT NULL,

    CONSTRAINT fk_test_questions_test FOREIGN KEY (test_id) REFERENCES tests(id) ON DELETE CASCADE,
    CONSTRAINT uk_test_questions_test_index UNIQUE (test_id, question_index),
    CONSTRAINT chk_test_questions_status CHECK (status IN ('OK', 'NEEDS_REVIEW'))
);

-- Most common query: load questions for a test ordered by question_index
CREATE INDEX idx_test_questions_test_id_question_index
ON test_questions(test_id, question_index);

CREATE INDEX idx_test_questions_tenant_test_id
ON test_questions(tenant_id, test_id);

-- Create generation_runs table (one row per LLM call)
CREATE TABLE generation_runs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id BIGINT NOT NULL,
    test_id BIGINT NOT NULL,
    question_id BIGINT,
    purpose VARCHAR(30) NOT NULL,
    batch_index INTEGER,
    model VARCHAR(100),
    prompt_template_id VARCHAR(100),
    retrieved_chunk_ids_json JSONB,
    raw_response TEXT,
    input_tokens INTEGER,
    output_tokens INTEGER,
    finish_reason VARCHAR(50),
    status VARCHAR(50) NOT NULL,
    error_message TEXT,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    created_by BIGINT NOT NULL,
    updated_by BIGINT NOT NULL,

    CONSTRAINT fk_generation_runs_test FOREIGN KEY (test_id) REFERENCES tests(id) ON DELETE CASCADE,
    CONSTRAINT fk_generation_runs_question FOREIGN KEY (question_id) REFERENCES test_questions(id) ON DELETE CASCADE,
    CONSTRAINT chk_generation_runs_status CHECK (status IN ('SUCCESS', 'FAILED')),
    CONSTRAINT chk_generation_runs_purpose CHECK (purpose IN ('TEST_GENERATION', 'REGENERATION', 'VERIFICATION'))
);

CREATE INDEX idx_generation_runs_test_id ON generation_runs(test_id);
CREATE INDEX idx_generation_runs_question_id ON generation_runs(question_id);
CREATE INDEX idx_generation_runs_status ON generation_runs(status);

-- Create test_question_versions table (immutable content snapshots)
CREATE TABLE test_question_versions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id BIGINT NOT NULL,
    question_id BIGINT NOT NULL,
    version_no INTEGER NOT NULL,
    origin VARCHAR(20) NOT NULL,
    parent_version_id BIGINT,
    generation_run_id BIGINT,
    verification_run_id BIGINT,
    question_text TEXT NOT NULL,
    explanation TEXT,
    source_chunk_ids_json JSONB,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    created_by BIGINT,  -- NULL = system (LLM generation)

    CONSTRAINT fk_tq_versions_question FOREIGN KEY (question_id) REFERENCES test_questions(id) ON DELETE CASCADE,
    CONSTRAINT fk_tq_versions_parent FOREIGN KEY (parent_version_id) REFERENCES test_question_versions(id) ON DELETE SET NULL,
    CONSTRAINT fk_tq_versions_generation_run FOREIGN KEY (generation_run_id) REFERENCES generation_runs(id) ON DELETE SET NULL,
    CONSTRAINT fk_tq_versions_verification_run FOREIGN KEY (verification_run_id) REFERENCES generation_runs(id) ON DELETE SET NULL,
    CONSTRAINT uk_tq_versions_question_version UNIQUE (question_id, version_no),
    CONSTRAINT chk_tq_versions_origin CHECK (origin IN ('GENERATED', 'REGENERATED', 'FIX_ACCEPTED', 'MANUAL')),
    CONSTRAINT chk_tq_versions_version_no CHECK (version_no > 0)
);

CREATE INDEX idx_tq_versions_question_id ON test_question_versions(question_id);

